"""Pack bounded RLE sound packets into explicitly unused SIC ROM ranges."""
import json
from pathlib import Path
R=Path(__file__).resolve().parents[1]
def pack(rom):
 ranges=[(26,0x3000,0x3f00),(27,0,0x3f00),(28,0x1800,0x3f00),(29,0x3900,0x3f00)]
 ranges += [(b,0x2900,0x3f00) for b in (2,4,5)]+[(1,0x2c00,0x3f00),(3,0x2c00,0x3000),(3,0x3c00,0x3f00),(6,0x2d00,0x2e00),(6,0x3990,0x3f00)]
 ends={b:0 for b in range(8,26)};ends[7]=0x3c00
 for b,n in json.loads((R/'assets/native-cache.json').read_text()).items():ends[int(b)]=max(ends[int(b)],n)
 ranges += [(b,n,0x3f00) for b,n in ends.items() if 0x3f00-n>=16]
 ranges += [(0,0x3000,0x3f00),(31,0x3a00,0x3f00)]
 # The common block includes rolling-ball flags through $2FBF.
 # It is copied to RAM at boot; its apparently unused tail is not audio space.
 protected=[(26,0,0x3000),(28,0,0x1800),(0,0x2000,0x3000),(30,0,0x3f00),(29,0,0x3900)]
 for bank_,lo_,hi_ in ranges:
  assert all(bank_!=b or hi_<=lo or lo_>=hi for b,lo,hi in protected), ('audio overlap',bank_,lo_,hi_)
 region=0;bank,pos,end=ranges[0];used=0;catalog=[]
 def reserve(n):
  nonlocal region,bank,pos,end,used
  while pos+n+4>end:
   region+=1
   if region==len(ranges):raise ValueError('Audio ROM overflow')
   bank,pos,end=ranges[region]
  a=(bank,pos);pos+=n;used+=n;return a
 def write(a,data):
  b,p=a;rom[b*16384+p:b*16384+p+len(data)]=bytes(data)
 def link(a,dest):
  write(a,[0,0x20|dest[0],(dest[1]+0x8000)&255,(dest[1]+0x8000)>>8] if dest else [0,0,0,0])
 for row in json.loads((R/'assets/audio/manifest.json').read_text()):
  data=json.loads((R/'assets/audio'/row['file']).read_text());addresses=[];prev=None;links=[]
  for packet in data['packets']:
   # Bit 7 of duration carries the ninth register-mask bit. Long delays
   # split into empty packets without changing a single output frame.
   duration,lo,hi,*values=packet
   assert 0 <= hi <= 1 and duration > 0
   first=True
   while duration:
    n=min(duration,127)
    encoded=[n|(hi<<7),lo]+values if first else [n,0]
    old=(bank,pos)
    a=reserve(len(encoded))
    if prev and a!=old:links.append((old,a))
    if first:addresses.append(a)
    write(a,encoded);prev=a
    first=False;duration-=n
  # reserve() always leaves four bytes for this terminal link.
  tail=(bank,pos);pos+=4;used+=4
  links.append((tail,None if data['loop_packet'] is None else addresses[data['loop_packet']]))
  for source,dest in links:link(source,dest)
  b,p=addresses[0];catalog.append((b|32,p&255,0x80+(p>>8)))
 text='; Generated by tools/pack_audio.py. NTSC 29 entries, then PAL 29.\n'
 for i,name in enumerate(('audio_bank','audio_lo','audio_hi')):
  text+=name+': .byte '+','.join(str(x[i]) for x in catalog)+'\n'
 # PCM uses short blocks so even fragmented cartridge tails can be used.
 pcm=(R/'assets/audio/applause.bin').read_bytes();chunks=[]
 i=0
 while i<len(pcm):
  while pos+5>end:
   region+=1
   if region==len(ranges):raise ValueError('Audio ROM overflow')
   bank,pos,end=ranges[region]
  n=min(128,len(pcm)-i,end-pos-4)
  block=pcm[i:i+n];a=reserve(n);write(a,block)
  chunks.append((a[0]|32,a[1]&255,0x80+(a[1]>>8),n));i+=n
 assert len(chunks)<256
 for i,name in enumerate(('pcm_bank','pcm_lo','pcm_hi','pcm_size')):
  text+=name+': .byte '+','.join(str(x[i]) for x in chunks)+'\n'
 text+='PCM_BLOCKS='+str(len(chunks))+'\n'
 (R/'build/audio_directory.inc').write_text(text)
 (R/'build/audio-packing.json').write_text(json.dumps({'bytes':used,'free_ranges':ranges,'catalog':catalog},indent=2))
 print('Audio packed:',used,'bytes')
 return rom
