"""Six-panel ANTIC-4 chooser from prepared, original arcade icon extracts.

No arcade ROM is needed. The source icons were captured from the user's
level-select set with ordinary coin/start/left/right input, without its cursor.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image, ImageDraw
from title_assets import packbits
R=Path(__file__).resolve().parents[1]
# Compact letters leave space for the arcade difficulty captions.
F={
'A':'010/101/111/101/101','B':'110/101/110/101/110','C':'011/100/100/100/011',
'D':'110/101/101/101/110','E':'111/100/110/100/111','F':'111/100/110/100/100',
'G':'011/100/101/101/011','H':'101/101/111/101/101','I':'111/010/010/010/111',
'J':'001/001/001/101/010','K':'101/101/110/101/101','L':'100/100/100/100/111',
'M':'101/111/111/101/101','N':'101/111/111/111/101','O':'010/101/101/101/010',
'P':'110/101/110/100/100','Q':'010/101/101/111/011','R':'110/101/110/101/101',
'S':'011/100/010/001/110','T':'111/010/010/010/010','U':'101/101/101/101/111',
'V':'101/101/101/101/010','W':'101/101/111/111/101','X':'101/101/010/101/101',
'Y':'101/101/010/010/010','Z':'111/001/010/100/111',
'1':'010/110/010/010/111','2':'110/001/010/100/111','3':'110/001/010/001/110',
'4':'101/101/111/001/001','5':'111/100/110/001/110','6':'011/100/110/101/010',
' ':'000/000/000/000/000'}
def text(a,s,x,y,c):
 for j,ch in enumerate(s):
  for dy,row in enumerate(F[ch].split('/')):
   for dx,v in enumerate(row):
    if v=='1':a[y+dy,x+j*4+dx]=c

def indexed(rgb,i):
 # White/light pink, red/orange, blue/cyan, and the ball's purple accent.
 v=rgb.astype(int);r,g,b=v[:,:,0],v[:,:,1],v[:,:,2];out=np.zeros(r.shape,np.uint8)
 lit=v.max(2)>60
 out[lit]=2
 out[lit&(r>g*1.5)&(r>b*1.3)]=1
 out[lit&(b>r*1.3)]=4
 out[lit&(g>r*1.3)&(b>r*1.2)]=4
 if i==3:out[lit&(r>g*1.3)&(b>g*1.3)]=3
 else:out[lit&(r>150)&(g>120)&(b<100)]=3
 return out

art=np.zeros((176,160),np.uint8);icons=np.load(R/'assets/chooser-icons.npz')
sizes=[(34,34),(23,32),(23,29),(23,44),(35,42),(39,49)]
for i in range(6):
 x=(i%3)*52;y=(i//3)*88
 # Original multicolour dotted marquee. There is one cell of right margin.
 for xx in range(1,51,4):art[y,x+xx:x+xx+2]=[4,3,1][(xx//4)%3];art[y+87,x+xx:x+xx+2]=[1,4,3][(xx//4)%3]
 for yy in range(4,84,4):
  art[y+yy:y+yy+2,x]=[4,3,1][(yy//4)%3];art[y+yy:y+yy+2,x+51]=[1,4,3][(yy//4)%3]
 label=f'{i+1} '+['EASY','NORMAL','NORMAL','HARD','HARDER','HARDEST'][i]
 text(art,label,x+(52-(len(label)*4-1))//2,y+8,3)
 # Act number is cyan, just as in the original menu.
 text(art,str(i+1),x+(52-(len(label)*4-1))//2,y+8,4)
 w,h=sizes[i];icon=np.array(Image.fromarray(indexed(icons[f'act{i}'],i)).resize((w,h),Image.Resampling.NEAREST))
 ix=x+(52-w)//2;iy=y+72-h
 art[iy:iy+h,ix:ix+w]=icon
 if i==1:art[y+73,x+3:x+49]=2
fonts=[];screen=[];counts=[];locks=[]
for band,(first,last) in enumerate([(0,8),(8,17),(17,22)]):
 patterns=[bytes(8)];lookup={bytes(8):0}
 def encode(tile):
  tile=tile.copy();alt=int(np.count_nonzero(tile==4)>np.count_nonzero(tile==3));tile[tile==(3 if alt else 4)]=2;tile[tile==4]=3
  pat=bytes(sum(int(v)<<(6-2*x) for x,v in enumerate(row)) for row in tile)
  if pat not in lookup:lookup[pat]=len(patterns);patterns.append(pat)
  return lookup[pat] | (128 if alt else 0)
 for row in range(first,last):
  for col in range(40):screen.append(encode(art[row*8:row*8+8,col*4:col*4+4]))
 if band<2:
  label=np.zeros((8,44),np.uint8);text(label,'NO MORE',8,0,1)
  locks.append([encode(label[:,c*4:c*4+4]) for c in range(11)])
 counts.append(len(patterns));assert len(patterns)<=112,counts
 data=bytearray(b''.join(patterns)).ljust(1024,b'\0')
 # 112..119: outline edges and corners; 120..121: progress dots.
 for code in range(112,122):
  tile=np.zeros((8,4),np.uint8)
  if code in (112,116,117):tile[0]=2
  if code in (113,118,119):tile[7]=2
  if code in (114,116,118):tile[:,0]=2
  if code in (115,117,119):tile[:,3]=2
  if code==120:tile[2:5,1:3]=2
  if code==121:tile[1:6,:]=2;tile[2:5,1:3]=0
  data[code*8:code*8+8]=bytes(sum(int(v)<<(6-2*x) for x,v in enumerate(row)) for row in tile)
 fonts.extend(data)
raw=bytes(fonts)+bytes(screen).ljust(1024,b'\0');encoded=packbits(raw)
(R/'assets/chooser.bin').write_bytes(encoded)
(R/'src/chooser-data.inc').write_text('; Generated by tools/chooser_assets.py.\nchooser_lock_top: .byte '+','.join(map(str,locks[0]))+'\nchooser_lock_bottom: .byte '+','.join(map(str,locks[1]))+'\n')
(R/'assets/chooser-info.json').write_text(json.dumps({'glyph_counts':counts,'raw_bytes':len(raw),'packed_bytes':len(encoded),'source':'User-supplied circusc level-select set; unselected arcade icons','panels':6},indent=2)+'\n')
pal=np.array([[0,0,0],[205,54,65],[245,242,236],[237,205,64],[41,165,226]],np.uint8);rgb=pal[art];mask=art[104:]==3;rgb[104:][mask]=[194,80,220]
Image.fromarray(rgb).resize((640,352),Image.Resampling.NEAREST).save(R/'build/chooser-art.png')
print('Chooser glyphs',counts,'packed',len(encoded))
